import {join,resolve} from 'node:path';
import {execFileSync,execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {once} from 'node:events';
import {loadApprovedSnapshot} from '../../tools/data-migration/approved-snapshot.mjs';
import {importBookingBindings} from '../../tools/data-migration/booking-bindings.mjs';
import {importApprovedSnapshot} from '../../tools/data-migration/import-snapshot.mjs';
import {createDatabase} from '../../services/payments-wallet/src/database.js';
import {migrate} from '../../services/payments-wallet/src/migrations.js';
import {createPaymentsRuntime} from '../../services/payments-wallet/src/runtime.js';
import {createFinancialOperations} from '../../services/payments-wallet/src/financial/index.js';
import {getDb,closeDb} from '../../bangkok-homeservice/lib/db/index.js';
import {createPaymentsClient} from '../../bangkok-homeservice/lib/modules/payments/client.js';
import {createFinancialClient} from '../../bangkok-homeservice/lib/modules/payments/financial-client.js';
import {configurePaymentsAccess,resetPaymentsAccess} from '../../bangkok-homeservice/lib/modules/payments/access.js';
import {createBookingFinalization,resetBookingFinalization,recoverFinalizationOnce} from '../../bangkok-homeservice/lib/modules/booking/finalization.js';
import {configureBookingFinancialAccess,resetBookingFinancialAccess,completeBookingFinancial,cancelBookingFinancial} from '../../bangkok-homeservice/lib/modules/booking/financial-access.js';
import {paymentSetupFor} from '../../bangkok-homeservice/lib/modules/booking/saga.js';
import {getBookingView,simulateBookingPayment} from '../../bangkok-homeservice/lib/modules/booking/payment-view.js';
test('approved old Bookings use real HTTP/PostgreSQL without invented sagas; partial checkpoint stays closed',async()=>{
 assert.ok(process.env.TEST_DATABASE_URL,'Dedicated disposable PostgreSQL required');
 const root=mkdtempSync(join(tmpdir(),'legacy-v11-e2e-'));let server,db;
 try{
  execFileSync('python3',['-B','-c',"from pathlib import Path; import sys; from test_export import make_source,module; p=Path(sys.argv[1]);make_source(p/'source.sqlite');module.export_snapshot(p/'source.sqlite',p/'snapshot',writers_stopped=True)",root],{cwd:new URL('../../tools/data-migration',import.meta.url)});
  const directory=join(root,'snapshot'),envelope=JSON.parse(readFileSync(join(directory,'manifest.json'),'utf8'));
  const approved=await loadApprovedSnapshot(directory,envelope.manifest_sha256);
  process.env.DB_PATH=join(root,'booking.sqlite');copyFileSync(join(directory,'source.sqlite'),process.env.DB_PATH);
  const sqlite=getDb();importBookingBindings(sqlite,approved,{apply:true});
  db=createDatabase(process.env.TEST_DATABASE_URL);await migrate(db);await importApprovedSnapshot(db,'payments-wallet',approved,{apply:true});
  const auth=async req=>{assert.equal(req.get('authorization'),'Bearer user-fixture');return{role:'customer',domainId:5};};
  const service=async req=>{assert.equal(req.get('authorization'),'Bearer service-fixture');return{service:'booking',callerId:'booking-legacy-e2e'};};
  const runtime=createPaymentsRuntime({database:db,createFinancialOperations,legacyManifestSha256:envelope.manifest_sha256,authenticate:auth,authenticateService:service});
  server=runtime.app.listen(0,'127.0.0.1');await once(server,'listening');
  const baseUrl=`http://127.0.0.1:${server.address().port}`;
  const paymentsClient=createPaymentsClient({baseUrl}),financial=createFinancialClient({baseUrl});
  configurePaymentsAccess({paymentsClient,credentials:async()=>({token:'user-fixture'}),readSetup:paymentSetupFor});
  const callbacks=()=>createBookingFinalization({financial,credentials:async()=>({token:'service-fixture'}),baseBackoffMs:1,maxBackoffMs:2});
  configureBookingFinancialAccess({bookingFinalization:callbacks()});
  const customer={role:'customer',sub:5},provider={role:'provider',sub:7};
  assert.equal((await getBookingView(13,customer)).payment_setup,'pending');
  await assert.rejects(simulateBookingPayment(13,customer));
  await assert.rejects(cancelBookingFinancial(13,customer));
  assert.equal(sqlite.prepare('SELECT count(*) n FROM booking_financial_work').get().n,0);
  // Represents the coordinated operator checkpoint; never performed by application HTTP.
  sqlite.prepare("UPDATE booking_legacy_payment_checkpoints SET state='approved'").run();
  configureLegacyBookingApproval(envelope.manifest_sha256);
  assert.equal((await getBookingView(13,customer)).payment_setup,'ready');
  const oldLedger=sqlite.prepare('SELECT * FROM transactions ORDER BY id').all();
  await simulateBookingPayment(13,customer);
  sqlite.prepare("INSERT INTO slot_holds(provider_id,service_date,slot_time,order_id) VALUES(7,'2026-11-10','10:00',13)").run();
  let dropResult=true;
  resetBookingFinalization();resetBookingFinancialAccess();
  const lossy=createFinancialClient({baseUrl,fetchImpl:async(...args)=>{const result=await fetch(...args);if(dropResult&&String(args[0]).endsWith('/internal/booking-cancellations')){dropResult=false;throw Error('lost reply after commit');}return result;}});
  configureBookingFinancialAccess({bookingFinalization:createBookingFinalization({financial:lossy,credentials:async()=>({token:'service-fixture'}),baseBackoffMs:1,maxBackoffMs:2})});
  const pending=await cancelBookingFinancial(13,customer);assert.equal(pending.cancellation_status,'pending');assert.equal(dropResult,false,'fixture must lose the committed cancellation reply');
  const saved=sqlite.prepare("SELECT command_id,request_json FROM booking_financial_work WHERE order_id=13").get();
  assert.equal(sqlite.prepare('SELECT count(*) n FROM slot_holds WHERE order_id=13').get().n,1);
  resetBookingFinancialAccess();resetBookingFinalization();configureBookingFinancialAccess({bookingFinalization:callbacks()});
  sqlite.prepare("UPDATE booking_financial_work SET next_attempt_at='2000-01-01' WHERE order_id=13").run();
  const finalizationUrl=new URL('../../bangkok-homeservice/lib/modules/booking/finalization.js',import.meta.url).href;
  const clientUrl=new URL('../../bangkok-homeservice/lib/modules/payments/financial-client.js',import.meta.url).href;
  const dbUrl=new URL('../../bangkok-homeservice/lib/db/index.js',import.meta.url).href;
  await promisify(execFile)(process.execPath,['--input-type=module','-e',`
    import {createBookingFinalization,recoverFinalizationOnce} from ${JSON.stringify(finalizationUrl)};
    import {createFinancialClient} from ${JSON.stringify(clientUrl)};
    import {closeDb} from ${JSON.stringify(dbUrl)};
    createBookingFinalization({financial:createFinancialClient({baseUrl:${JSON.stringify(baseUrl)}}),credentials:async()=>({token:'service-fixture'})});
    await recoverFinalizationOnce();closeDb();
  `],{env:{...process.env,DB_PATH:process.env.DB_PATH},timeout:15000});
  assert.equal(sqlite.prepare('SELECT status FROM orders WHERE id=13').get().status,'cancelled');
  assert.equal(sqlite.prepare('SELECT count(*) n FROM slot_holds WHERE order_id=13').get().n,0);
  assert.deepEqual(sqlite.prepare('SELECT command_id,request_json FROM booking_financial_work WHERE order_id=13').get(),saved);
  sqlite.prepare("UPDATE orders SET status='started' WHERE id=14").run();
  const complete=await completeBookingFinancial(14,provider,123456);assert.equal(complete.accounting_status,'ready');
  await completeBookingFinancial(14,provider,123456);
  const kinds=(await db.query('SELECT order_id,kind,count(*)::int n FROM transactions WHERE order_id IN(13,14) GROUP BY order_id,kind ORDER BY order_id,kind')).rows;
  assert.deepEqual(kinds,[{order_id:13,kind:'charge',n:1},{order_id:13,kind:'refund',n:1},{order_id:14,kind:'charge',n:1},{order_id:14,kind:'payout_credit',n:1}]);
  assert.equal(sqlite.prepare('SELECT count(*) n FROM booking_sagas').get().n,0);
  assert.equal((await db.query('SELECT count(*)::int n FROM payment_provisioning')).rows[0].n,0);
  assert.deepEqual(sqlite.prepare('SELECT * FROM transactions ORDER BY id').all(),oldLedger);
 }finally{
  resetLegacyBookingApproval();resetBookingFinancialAccess();resetBookingFinalization();resetPaymentsAccess();closeDb();delete process.env.DB_PATH;
  if(server){server.closeAllConnections();await new Promise(resolve=>server.close(resolve));}await db?.close();rmSync(root,{recursive:true,force:true});
 }
});
